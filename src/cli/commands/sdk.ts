import path from "node:path";
import { existsSync, writeFileSync, mkdirSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { createJiti } from "jiti";
import { loadConfig } from "../config.js";
import { collectTables } from "../../compiler/compile.js";
import type { Column } from "../../core/column.js";
import type { TableImpl } from "../../core/table.js";

type AnyCol = Column<any, any, any>;

function pascalCase(name: string): string {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

function literal(value: string): string {
  return JSON.stringify(value);
}

function resolveBaseType(col: AnyCol, byCol: Map<AnyCol, AnyCol>): string {
  const state = col.state;
  if (state.isRef) {
    const thunk = state.referencesThunk;
    if (thunk) {
      try {
        const target = thunk() as AnyCol;
        return resolveBaseType(target, byCol);
      } catch {
        return "unknown";
      }
    }
    return "unknown";
  }
  switch (state.kind) {
    case "id":
    case "int":
    case "real":
      return "number";
    case "bigint":
      return "bigint";
    case "bool":
      return "boolean";
    case "timestamp":
      return "Date";
    case "uuid":
    case "text":
    case "varchar":
      return "string";
    case "enum": {
      const vals = state.enumValues ?? [];
      if (vals.length === 0) return "string";
      return vals.map(literal).join(" | ");
    }
    case "json":
      return "unknown";
    default:
      return "unknown";
  }
}

export async function runSdk(cwd: string = process.cwd(), outFile?: string): Promise<string> {
  const cfg = await loadConfig(cwd);
  const schemaPath = path.resolve(cwd, cfg.schema);
  if (!existsSync(schemaPath)) throw new Error(`Schema file not found: ${schemaPath}`);
  const jiti = createJiti(pathToFileURL(schemaPath).href, { moduleCache: false });
  const mod = (await jiti.import(schemaPath)) as Record<string, unknown>;
  const tables = collectTables(mod) as TableImpl<any>[];

  const defaultOut = path.join(path.dirname(schemaPath), "sdk.gen.ts");
  const outPath = outFile ? path.resolve(cwd, outFile) : defaultOut;
  mkdirSync(path.dirname(outPath), { recursive: true });

  const byCol = new Map<AnyCol, AnyCol>();
  for (const t of tables) {
    for (const c of Object.values(t.columns)) byCol.set(c as AnyCol, c as AnyCol);
  }

  const lines: string[] = [];
  lines.push("// Generated by duronto sdk. Do not edit.");
  lines.push("// This file is dependency-free (no import of duronto at runtime).");
  lines.push("");

  for (const t of tables) {
    const pascal = pascalCase(t.tableName);
    const entries = Object.keys(t.columns)
      .sort()
      .map((key) => {
        const col = t.columns[key] as AnyCol;
        return { key, col, base: resolveBaseType(col, byCol) };
      });

    lines.push("/** What you read from the DB */");
    lines.push(`export type ${pascal} = {`);
    for (const e of entries) {
      const type = e.col.state.notNullFlag ? e.base : `${e.base} | null`;
      lines.push(`  ${e.key}: ${type};`);
    }
    lines.push("};");
    lines.push("");

    lines.push("/** What you pass to INSERT */");
    lines.push(`export type New${pascal} = {`);
    for (const e of entries) {
      const notNull = e.col.state.notNullFlag;
      const hasDefault = e.col.state.hasDefaultFlag;
      const type = notNull ? e.base : `${e.base} | null`;
      if (hasDefault || !notNull) {
        lines.push(`  ${e.key}?: ${type};`);
      } else {
        lines.push(`  ${e.key}: ${type};`);
      }
    }
    lines.push("};");
    lines.push("");

    lines.push("/** Partial update: all fields optional */");
    lines.push(`export type ${pascal}Patch = {`);
    for (const e of entries) {
      const type = e.col.state.notNullFlag ? e.base : `${e.base} | null`;
      lines.push(`  ${e.key}?: ${type};`);
    }
    lines.push("};");
    lines.push("");
  }

  const tableNames = tables.map((t) => t.tableName).sort();
  lines.push(`export const Tables = ${JSON.stringify(tableNames)} as const;`);
  lines.push("");

  writeFileSync(outPath, lines.join("\n"));
  return outPath;
}
