import path from "node:path";
import { existsSync, writeFileSync, mkdirSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { createJiti } from "jiti";
import { loadConfig } from "../config.js";
import { collectTables } from "../../compiler/compile.js";

export async function runTypes(cwd: string = process.cwd(), outFile?: string): Promise<string> {
  const cfg = await loadConfig(cwd);
  const schemaPath = path.resolve(cwd, cfg.schema);
  if (!existsSync(schemaPath)) throw new Error(`Schema file not found: ${schemaPath}`);
  const jiti = createJiti(pathToFileURL(schemaPath).href, { moduleCache: false });
  const mod = (await jiti.import(schemaPath)) as Record<string, unknown>;
  const tables = collectTables(mod);

  const defaultOut = path.join(path.dirname(schemaPath), "schema.gen.d.ts");
  const outPath = outFile ? path.resolve(cwd, outFile) : defaultOut;
  mkdirSync(path.dirname(outPath), { recursive: true });

  const lines: string[] = [];
  lines.push("// Generated by duronto. Do not edit.");
  lines.push(`import { ${tables.map((t) => t.tableName).join(", ")} } from "./${path.basename(schemaPath, ".ts")}";`);
  lines.push("");
  for (const t of tables) {
    const name = t.tableName;
    const pascal = name.charAt(0).toUpperCase() + name.slice(1);
    lines.push(`export type ${pascal} = import("duronto").InferSelect<typeof ${name}>;`);
    lines.push(`export type New${pascal} = import("duronto").InferInsert<typeof ${name}>;`);
    lines.push(`export type ${pascal}Patch = import("duronto").InferUpdate<typeof ${name}>;`);
  }
  writeFileSync(outPath, lines.join("\n") + "\n");
  return outPath;
}